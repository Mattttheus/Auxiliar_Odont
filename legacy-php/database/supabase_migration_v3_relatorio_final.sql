-- ============================================================
-- 8) MOVIMENTAÇÃO TRANSACIONAL (entrada/saída com lotes FEFO)
-- ============================================================
-- Tudo acontece numa única transação: trava a linha do produto, valida
-- permissão e estoque, atualiza lotes, quantidade, validade mais próxima,
-- e registra entradas/saidas + historico. Evita estoque inconsistente
-- quando duas pessoas movimentam o mesmo item ao mesmo tempo.
create or replace function public.registrar_movimentacao(
  p_produto_id bigint,
  p_tipo text,
  p_quantidade integer,
  p_observacao text default null,
  p_lote text default null,
  p_validade date default null,
  p_origem text default 'manual'
) returns integer
language plpgsql security definer set search_path = public as $$
declare
  v_user usuarios%rowtype;
  v_prod produtos%rowtype;
  v_novo integer;
  v_restante integer;
  v_tira integer;
  v_l record;
  v_lote text;
  v_lotes_usados text := '';
  v_descricao text;
  v_origem text := coalesce(nullif(trim(p_origem), ''), 'manual');
begin
  select * into v_user from usuarios where id = auth.uid();
  if not found or not v_user.ativo then
    raise exception 'Usuário sem perfil ativo no sistema.';
  end if;
  if p_tipo not in ('entrada', 'saida') then
    raise exception 'Tipo de movimentação inválido: %', p_tipo;
  end if;
  if p_quantidade is null or p_quantidade <= 0 then
    raise exception 'A quantidade deve ser maior que zero.';
  end if;
  if p_tipo = 'entrada' and v_user.role not in ('admin', 'estoquista') then
    raise exception 'Seu nível de acesso não permite registrar entradas.';
  end if;
  if p_tipo = 'saida' and v_user.role not in ('admin', 'estoquista', 'vendedor') then
    raise exception 'Seu nível de acesso não permite registrar saídas.';
  end if;

  select * into v_prod from produtos where id = p_produto_id for update;
  if not found then
    raise exception 'Produto não encontrado.';
  end if;

  -- Sinaliza ao gatilho de auditoria que esta alteração de quantidade é
  -- uma movimentação (já registrada abaixo), e não um ajuste manual.
  perform set_config('app.movimentacao', 'on', true);

  if p_tipo = 'entrada' then
    v_novo := v_prod.quantidade + p_quantidade;
    v_lote := nullif(trim(p_lote), '');
    if v_lote is not null or p_validade is not null then
      v_lote := coalesce(v_lote, 'S/L');
      update lotes set quantidade = quantidade + p_quantidade, atualizado_em = now()
      where produto_id = p_produto_id and lote = v_lote and validade is not distinct from p_validade;
      if not found then
        insert into lotes (produto_id, lote, validade, quantidade)
        values (p_produto_id, v_lote, p_validade, p_quantidade);
      end if;
    end if;

    insert into entradas_produtos (produto_id, produto_nome, quantidade, usuario_id, usuario_nome, observacao, lote, validade, origem)
    values (p_produto_id, v_prod.nome, p_quantidade, v_user.id, v_user.nome, coalesce(p_observacao, ''), v_lote, p_validade, v_origem);

    v_descricao := 'Entrada de ' || p_quantidade || ' unidade(s)'
      || coalesce(' — lote ' || v_lote, '')
      || coalesce(' — validade ' || to_char(p_validade, 'DD/MM/YYYY'), '');
  else
    if p_quantidade > v_prod.quantidade then
      raise exception 'Estoque insuficiente para "%". Disponível: %', v_prod.nome, v_prod.quantidade;
    end if;
    v_novo := v_prod.quantidade - p_quantidade;

    -- FEFO: consome primeiro os lotes que vencem antes.
    v_restante := p_quantidade;
    for v_l in
      select id, lote, quantidade from lotes
      where produto_id = p_produto_id and quantidade > 0
      order by validade nulls last, id
      for update
    loop
      exit when v_restante = 0;
      v_tira := least(v_restante, v_l.quantidade);
      update lotes set quantidade = quantidade - v_tira, atualizado_em = now() where id = v_l.id;
      v_restante := v_restante - v_tira;
      v_lotes_usados := v_lotes_usados || case when v_lotes_usados = '' then '' else ', ' end
        || v_l.lote || ' (' || v_tira || ')';
    end loop;

    insert into saidas_produtos (produto_id, produto_nome, quantidade, usuario_id, usuario_nome, observacao, lote, origem)
    values (p_produto_id, v_prod.nome, p_quantidade, v_user.id, v_user.nome, coalesce(p_observacao, ''), nullif(v_lotes_usados, ''), v_origem);

    v_descricao := 'Saída de ' || p_quantidade || ' unidade(s)'
      || coalesce(' — lote(s) ' || nullif(v_lotes_usados, ''), '');
  end if;

  -- A validade exibida no produto passa a ser a do lote ativo que vence primeiro.
  update produtos set
    quantidade = v_novo,
    atualizado_em = now(),
    validade = case
      when exists (select 1 from lotes where produto_id = p_produto_id)
        then (select min(validade) from lotes where produto_id = p_produto_id and quantidade > 0)
      else v_prod.validade
    end
  where id = p_produto_id;

  insert into historico (usuario_id, usuario_nome, produto_id, produto_nome, acao, descricao, quantidade, origem)
  values (v_user.id, v_user.nome, p_produto_id, v_prod.nome,
          case when p_tipo = 'entrada' then 'Entrada' else 'Saída' end,
          v_descricao,
          case when p_tipo = 'entrada' then p_quantidade else -p_quantidade end,
          v_origem);

  return v_novo;
end;
$$;

-- Venda do Caixa (PDV): todos os itens numa única transação — ou sai tudo,
-- ou nada (antes, uma falha no meio deixava parte do carrinho baixada).
create or replace function public.registrar_venda(
  p_itens jsonb,
  p_observacao text default 'Venda via Caixa (PDV)'
) returns integer
language plpgsql security definer set search_path = public as $$
declare
  v_item record;
  v_n integer := 0;
begin
  for v_item in
    select * from jsonb_to_recordset(p_itens) as x(produto_id bigint, quantidade integer)
  loop
    perform public.registrar_movimentacao(v_item.produto_id, 'saida', v_item.quantidade, p_observacao, null, null, 'pdv');
    v_n := v_n + 1;
  end loop;
  return v_n;
end;
$$;

-- Recebimento de uma lista de compras: dá entrada de todos os itens e
-- marca a lista como recebida, numa única transação.
create or replace function public.receber_lista_compra(p_lista_id bigint)
returns integer
language plpgsql security definer set search_path = public as $$
declare
  v_status text;
  v_item record;
  v_n integer := 0;
begin
  if coalesce(public.get_my_role(), '') not in ('admin', 'estoquista') then
    raise exception 'Seu nível de acesso não permite receber compras.';
  end if;
  select status into v_status from listas_compra where id = p_lista_id for update;
  if not found then
    raise exception 'Lista de compras não encontrada.';
  end if;
  if v_status in ('recebida', 'cancelada') then
    raise exception 'Esta lista já está %.', v_status;
  end if;

  for v_item in
    select produto_id, quantidade from listas_compra_itens
    where lista_id = p_lista_id and produto_id is not null
  loop
    perform public.registrar_movimentacao(v_item.produto_id, 'entrada', v_item.quantidade,
      'Recebimento da lista de compras #' || p_lista_id, null, null, 'compra');
    v_n := v_n + 1;
  end loop;

  update listas_compra set status = 'recebida', recebida_em = now(), atualizado_em = now()
  where id = p_lista_id;
  return v_n;
end;
$$;

