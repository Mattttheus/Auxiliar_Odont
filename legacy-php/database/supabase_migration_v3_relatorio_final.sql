  for each row execute function public.auditar_produtos();
drop trigger if exists trg_auditar_produtos_upd on produtos;
create trigger trg_auditar_produtos_upd after update on produtos
  for each row execute function public.auditar_produtos();
drop trigger if exists trg_auditar_produtos_del on produtos;
create trigger trg_auditar_produtos_del after delete on produtos
  for each row execute function public.auditar_produtos();

