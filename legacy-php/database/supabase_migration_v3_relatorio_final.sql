-- ============================================================
-- 9) ANÁLISE AUTOMÁTICA DO ESTOQUE → SUGESTÃO DE COMPRA
-- ============================================================
-- Para cada produto:
--   consumo_diario  = saídas na janela configurada / dias da janela
--   qtd_vencendo    = unidades em lotes que vencem dentro do alerta de validade
--   estoque_util    = quantidade - qtd_vencendo (o que vai vencer não conta)
--   ponto_pedido    = estoque_minimo + consumo durante o prazo de entrega
--   alvo            = estoque_minimo + max(consumo na cobertura+entrega, estoque_minimo)
--   sugerido        = alvo - estoque_util, quando estoque_util <= ponto_pedido
-- Sem histórico de consumo, o alvo é o dobro do estoque mínimo.
create or replace function public.sugerir_lista_compras()
returns table (
  produto_id bigint,
  nome text,
  categoria text,
  unidade text,
  localizacao text,
  quantidade integer,
  estoque_minimo integer,
  consumo_periodo integer,
  consumo_diario numeric,
  validade_proxima date,
  qtd_vencendo integer,
  estoque_util integer,
  quantidade_sugerida integer,
  motivo text
)
language sql stable set search_path = public as $$
  with cfg as (
    select * from configuracoes where id = 1
  ),
  consumo as (
    select s.produto_id, sum(s.quantidade)::integer as total
    from saidas_produtos s, cfg
    where s.data_saida >= now() - make_interval(days => cfg.janela_consumo_dias)
    group by s.produto_id
  ),
  venc as (
    select l.produto_id,
           min(l.validade) as validade_proxima,
           coalesce(sum(l.quantidade) filter (where l.validade <= current_date + cfg.dias_alerta_validade), 0)::integer as qtd_vencendo
    from lotes l, cfg
    where l.quantidade > 0 and l.validade is not null
    group by l.produto_id
  ),
  base as (
    select p.id, p.nome, p.categoria, p.unidade, p.localizacao, p.quantidade, p.estoque_minimo,
           coalesce(c.total, 0) as consumo_periodo,
           round(coalesce(c.total, 0)::numeric / cfg.janela_consumo_dias, 3) as consumo_diario,
           coalesce(v.validade_proxima, p.validade) as validade_proxima,
           least(p.quantidade, coalesce(v.qtd_vencendo,
             case when p.validade is not null and p.validade <= current_date + cfg.dias_alerta_validade
                  then p.quantidade else 0 end)) as qtd_vencendo,
           cfg.dias_cobertura, cfg.dias_reposicao, cfg.janela_consumo_dias
    from produtos p
    cross join cfg
    left join consumo c on c.produto_id = p.id
    left join venc v on v.produto_id = p.id
  ),
  calc as (
    select b.*,
           b.quantidade - b.qtd_vencendo as util,
           b.estoque_minimo + ceil(b.consumo_diario * b.dias_reposicao)::integer as ponto_pedido,
           b.estoque_minimo + greatest(ceil(b.consumo_diario * (b.dias_cobertura + b.dias_reposicao))::integer, b.estoque_minimo) as alvo
    from base b
  )
  select id, nome, categoria, unidade, localizacao, quantidade, estoque_minimo,
         consumo_periodo, consumo_diario, validade_proxima, qtd_vencendo, util,
         (alvo - util) as quantidade_sugerida,
         concat_ws(' · ',
           case when quantidade = 0 then 'Sem estoque'
                when quantidade <= estoque_minimo then 'Abaixo do mínimo' end,
           case when qtd_vencendo > 0 then qtd_vencendo || ' un. vencem até ' || to_char(validade_proxima, 'DD/MM/YYYY') end,
           case when consumo_periodo > 0 then 'Consumo: ' || consumo_periodo || ' un. em ' || janela_consumo_dias || ' dias' end
         ) as motivo
  from calc
  where util <= ponto_pedido and alvo - util > 0
  order by (quantidade = 0) desc, (util::numeric / nullif(alvo, 0)) nulls last, nome;
$$;

grant execute on function public.sugerir_lista_compras() to authenticated;

-- ============================================================
-- 10) AUDITORIA AUTOMÁTICA DE PRODUTOS
-- ============================================================
-- Cadastro, edição, ajuste manual de quantidade e exclusão viram registros
-- no histórico, mesmo que a alteração não venha da tela do sistema.
create or replace function public.auditar_produtos()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  v_nome text;
begin
  select nome into v_nome from usuarios where id = auth.uid();
  v_nome := coalesce(v_nome, 'Sistema');

  if TG_OP = 'INSERT' then
    insert into historico (usuario_id, usuario_nome, produto_id, produto_nome, acao, descricao, quantidade, origem)
    values (auth.uid(), v_nome, new.id, new.nome, 'Cadastro',
            'Produto cadastrado com ' || new.quantidade || ' unidade(s)', new.quantidade, 'cadastro');
    return new;
  elsif TG_OP = 'UPDATE' then
    if coalesce(current_setting('app.movimentacao', true), '') = 'on' then
      return new;
    end if;
    if new.quantidade is distinct from old.quantidade then
      insert into historico (usuario_id, usuario_nome, produto_id, produto_nome, acao, descricao, quantidade, origem)
      values (auth.uid(), v_nome, new.id, new.nome, 'Ajuste',
              'Ajuste manual de estoque: ' || old.quantidade || ' → ' || new.quantidade,
              new.quantidade - old.quantidade, 'ajuste');
    elsif row(new.nome, new.descricao, new.preco, new.categoria, new.unidade, new.estoque_minimo,
              new.validade, new.codigo_barras, new.localizacao)
          is distinct from
          row(old.nome, old.descricao, old.preco, old.categoria, old.unidade, old.estoque_minimo,
              old.validade, old.codigo_barras, old.localizacao) then
      insert into historico (usuario_id, usuario_nome, produto_id, produto_nome, acao, descricao, origem)
      values (auth.uid(), v_nome, new.id, new.nome, 'Edição', 'Dados do produto atualizados', 'cadastro');
    end if;
    return new;
  else
    insert into historico (usuario_id, usuario_nome, produto_id, produto_nome, acao, descricao, quantidade, origem)
    values (auth.uid(), v_nome, null, old.nome, 'Exclusão',
            'Produto excluído (tinha ' || old.quantidade || ' unidade(s))', -old.quantidade, 'cadastro');
    return old;
  end if;
end;
$$;

