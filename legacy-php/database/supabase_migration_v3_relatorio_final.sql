create table if not exists lotes (
  id bigint generated by default as identity primary key,
  produto_id bigint not null references produtos(id) on delete cascade,
  lote text not null default 'S/L',
  validade date,
  quantidade integer not null default 0 check (quantidade >= 0),
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

-- Estoque que já tinha validade vira um lote "INICIAL" (só na 1ª execução).
insert into lotes (produto_id, lote, validade, quantidade)
select p.id, 'INICIAL', p.validade, p.quantidade
from produtos p
where p.validade is not null and p.quantidade > 0
  and not exists (select 1 from lotes l where l.produto_id = p.id);

