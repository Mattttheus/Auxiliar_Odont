-- MIGRAÇÃO v3 — alinhamento com o Relatório Final do PI3 ("Gestão Odonto").
-- Execute este arquivo INTEIRO de uma vez no Supabase:
-- SQL Editor > New query > cole tudo > Run.
--
-- Pré-requisito: supabase_schema.sql e supabase_migration_v2_seguranca_estoque.sql.
-- Idempotente: pode ser reexecutado sem erro e sem duplicar dados.
--
-- O relatório descreve funcionalidades que passam a ser registradas e
-- indexadas no banco (e não só calculadas na tela):
--   1) Localização física do item (prateleira/armário), como no protótipo
--      (tabela "componentes": nome, quantidade, localizacao).
--   2) Acompanhamento de LOTES e datas de validade, com saída FEFO
--      (o lote que vence primeiro sai primeiro).
--   3) Movimentações de entrada/saída TRANSACIONAIS no banco (RPC), com
--      origem registrada (manual, QR, PDV, compra, importação).
--   4) Auditoria automática de cadastro/edição/ajuste/exclusão de produtos.
--   5) Critérios de reposição configuráveis (validade, consumo, cobertura,
--      prazo de entrega) — ajuste pedido no feedback do consultório.
--   6) Geração automática da LISTA DE COMPRAS por rotina SQL, baseada em
--      estoque mínimo, consumo real e proximidade da validade; listas
--      salvas com status e recebimento que dá entrada no estoque.
--   7) Índices para as consultas de histórico, validade e consumo.

